def _bigrams(text: str) -> set[str]:
    clean = re.sub(r"[\s，。！？、,.!?…「」“”\"']", "", text)
    return {clean[i:i + 2] for i in range(len(clean) - 1)}


class _Keep(dict):
    """展开已知槽位，保留运行时占位符（player_name / last_player）。"""

    def __missing__(self, key):
        return "{" + key + "}"


def _frame_variants(frame: str, slots: dict[str, list[str]]) -> list[str]:
    keys = re.findall(r"\{([a-zA-Z_][a-zA-Z0-9_]*)\}", frame)
    keys = [key for key in dict.fromkeys(keys) if key in slots]
    if not keys:
        return [frame]
    out = []
    for combo in itertools.product(*(slots[key] for key in keys)):
        out.append(frame.format_map(_Keep(dict(zip(keys, combo)))))
    return out


